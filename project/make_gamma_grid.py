"""
Generate eo_gamma_data.js: gamma_EO (original UNIFAC, thermo.unifac) for EO dissolved in EG-(EO)n (PEG).

EO      = CH2 + CH2O                      (groups 2, 25)
EG-(EO)n = 2 OH + (n+2) CH2 + n CH2O      (groups 14, 2, 25); n = 0 is ethylene glycol (2 OH + 2 CH2)
Grid: n (EO units per chain) x EO mole fraction x temperature; the JS tool interpolates trilinearly in
(ln(1+n), x, T). Long-chain values are an extrapolation of a method validated only at low adduct numbers
(Di Serio 1996) -- see CLAUDE.md.
"""
import json
import numpy as np
from thermo.unifac import UNIFAC

N_GRID = [0, 1, 2, 3, 4, 6, 8, 12, 16, 24, 32, 48, 64, 90]
X_GRID = [0.005, 0.02, 0.05, 0.10, 0.15, 0.20, 0.30, 0.45, 0.60, 0.80, 0.95, 0.995]
T_GRID = [290.0, 330.0, 370.0, 410.0, 450.0, 490.0]


def gamma_eo(T, x, n):
    poly = {14: 2, 2: 2} if n == 0 else {14: 2, 2: n + 2, 25: n}
    u = UNIFAC.from_subgroups(T=T, xs=[x, 1.0 - x], chemgroups=[{2: 1, 25: 1}, poly], version=0)
    return float(u.gammas()[0])


if __name__ == "__main__":
    g = [[[round(gamma_eo(T, x, n), 5) for T in T_GRID] for x in X_GRID] for n in N_GRID]  # [n][x][T]
    flat = [v for a in g for b in a for v in b]
    js = ("// Generated by make_gamma_grid.py (thermo.unifac, original UNIFAC). gamma_EO in EG-(EO)n.\n"
          "var EO_GAMMA = " + json.dumps({"n": N_GRID, "x": X_GRID, "T": T_GRID, "g": flat}) + ";\n"
          "if (typeof window !== 'undefined') window.EO_GAMMA = EO_GAMMA;\n"
          "if (typeof module !== 'undefined' && module.exports) module.exports = EO_GAMMA;\n")
    open("eo_gamma_data.js", "w", encoding="utf-8").write(js)
    print("wrote eo_gamma_data.js:", len(flat), "values; min/max gamma %.3f / %.3f" % (min(flat), max(flat)))
